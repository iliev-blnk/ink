// Renders one frame of ink per look in Chromium and saves it as text, for browsers without WebGL2.
// Usage: pnpm build:demo && node scripts/still.mjs
import { writeFileSync } from "node:fs";
import { chromium } from "playwright-core";
import { serve } from "../e2e/serve.mjs";

const RAMP = " .,:;-=+*x#%@";
const CELL = { w: 7, h: 12 }, VIEW = { width: 1440, height: 900 };
const AREA = { c0: 70, c1: 205, r0: 2, r1: 72 };
const PAPER = { night: [11, 11, 12], blue: [255, 255, 255] };
const port = 4482, server = await serve("dist-demo", port);
const browser = await chromium.launch({ executablePath: process.env.INK_CHROME ?? "/usr/bin/chromium", args: ["--use-angle=gl", "--ignore-gpu-blocklist"] });
const out = {};
for (const look of ["night", "blue"]) {
  const page = await browser.newPage({ viewport: VIEW, deviceScaleFactor: 1 });
  await page.goto(`http://127.0.0.1:${port}/?look=${look}&seed=7`);
  await page.waitForTimeout(7000);
  const ink = await page.evaluate(({ CELL, AREA, paper }) => {
    const c = document.querySelector("canvas"), x = document.createElement("canvas");
    x.width = c.width; x.height = c.height;
    const g = x.getContext("2d"); g.drawImage(c, 0, 0);
    const d = g.getImageData(0, 0, x.width, x.height).data, rows = [];
    for (let r = AREA.r0; r < AREA.r1; r++) {
      const row = [];
      for (let col = AREA.c0; col < AREA.c1; col++) {
        let sum = 0;
        for (let y = 0; y < CELL.h; y++) for (let k = 0; k < CELL.w; k++) {
          const i = ((r * CELL.h + y) * x.width + col * CELL.w + k) * 4;
          sum += Math.abs(d[i] - paper[0]) + Math.abs(d[i + 1] - paper[1]) + Math.abs(d[i + 2] - paper[2]);
        }
        row.push(sum / (CELL.w * CELL.h * 3 * 255));
      }
      rows.push(row);
    }
    return rows;
  }, { CELL, AREA, paper: PAPER[look] });
  const max = Math.max(...ink.flat()) || 1;
  out[look] = ink.map((row) => row.map((v) => RAMP[Math.min(RAMP.length - 1, Math.round(Math.sqrt(v / max) * (RAMP.length - 1)))]).join("").trimEnd()).join("\n");
  await page.close();
}
await browser.close();
server.close();
writeFileSync("src/still.ts", `// Generated by scripts/still.mjs: one frame of ink per look, for browsers without WebGL2.\nexport const STILL = ${JSON.stringify(out, null, 2)};\n`);
console.log("wrote src/still.ts", Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.length])));
